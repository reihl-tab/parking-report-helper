"""Fixed man-page date policy (#206): deterministic generation and drift.

The page date is the fixed PAGE_DATE in scripts/gen_manpages.py; it is bumped
by hand with a release (docs/CLI-CONTRACT.md, "Page date"). These tests pin
that the generated bytes depend on PAGE_DATE only: not on repeated runs, the
environment (TZ, locale, SOURCE_DATE_EPOCH, unrelated variables) or the wall
clock, and that --check catches a page that no longer matches. Offline,
synthetic and temp-dir only; the committed man/ tree is read, never written.
"""

import contextlib
import hashlib
import importlib.util
import io
import os
import re
import shutil
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "gen_manpages.py"
MAN1 = ROOT / "man" / "man1"
SHIPPED = ("p106-stats.1", "parking-report.1", "parking-report-106.1", "parking-report-http.1")
OTHER_DATE = "1999-12-31"
DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def load():
    spec = importlib.util.spec_from_file_location("gen_manpages_206", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = load()


def quiet_log():
    return gen.Log(False)


def base_env(**extra):
    env = {
        "PATH": os.environ.get("PATH", ""),
        "PYTHONPATH": os.environ.get("PYTHONPATH", ""),
        "PYTHONDONTWRITEBYTECODE": "1",
    }
    env.update(extra)
    return env


# Unrelated environment differences that must not reach the pages.
NOISY_ENV = {
    "TZ": "Pacific/Kiritimati",
    "LANG": "he_IL.UTF-8",
    "LC_ALL": "fr_FR.UTF-8",
    "LC_TIME": "ja_JP.UTF-8",
    "SOURCE_DATE_EPOCH": "0",
    "COLUMNS": "33",
    "PLH_UNRELATED_206": "synthetic-unrelated-value",
}

# Runs the generator with the wall clock moved: time.* and datetime's
# now/today/utcnow return the given epoch. Installed before the package is
# imported, so `from datetime import datetime` in its modules sees it too.
FAKE_CLOCK = textwrap.dedent(
    """
    import datetime, runpy, sys, time

    FIXED = float(sys.argv.pop(1))
    _localtime, _gmtime, _strftime = time.localtime, time.gmtime, time.strftime
    _ctime = time.ctime

    def _secs(value=None):
        return FIXED if value is None else value

    time.time = lambda: FIXED
    time.time_ns = lambda: int(FIXED * 1_000_000_000)
    time.localtime = lambda secs=None: _localtime(_secs(secs))
    time.gmtime = lambda secs=None: _gmtime(_secs(secs))
    time.ctime = lambda secs=None: _ctime(_secs(secs))
    time.strftime = lambda fmt, t=None: _strftime(fmt, _localtime(FIXED) if t is None else t)

    class FakeDateTime(datetime.datetime):
        @classmethod
        def now(cls, tz=None):
            return cls.fromtimestamp(FIXED, tz)

        @classmethod
        def utcnow(cls):
            return cls.utcfromtimestamp(FIXED)

        @classmethod
        def today(cls):
            return cls.fromtimestamp(FIXED)

    class FakeDate(datetime.date):
        @classmethod
        def today(cls):
            return cls.fromtimestamp(FIXED)

    datetime.datetime = FakeDateTime
    datetime.date = FakeDate
    sys.stderr.write(f"clock={datetime.date.today().isoformat()}\\n")
    sys.argv[0] = sys.argv[1]
    del sys.argv[1]
    try:
        runpy.run_path(sys.argv[0], run_name="__main__")
    finally:
        seen = sys.modules["parking_report.api_cli"].datetime.now().date()
        sys.stderr.write(f"package_clock={seen.isoformat()}\\n")
    """
)


def run_gen(*args, env, clock=None):
    if clock is None:
        cmd = [sys.executable, str(SCRIPT), *args]
    else:
        cmd = [sys.executable, "-c", FAKE_CLOCK, str(clock), str(SCRIPT), *args]
    return subprocess.run(
        cmd, capture_output=True, text=True, env=env, timeout=120, check=False
    )


def read_tree(directory):
    return {p.name: p.read_bytes() for p in sorted(Path(directory).glob("*.1"))}


def sha256_tree(directory):
    return {
        name: hashlib.sha256(data).hexdigest()
        for name, data in read_tree(directory).items()
    }


def th_line(text):
    return next(line for line in text.splitlines() if line.startswith(".TH "))


class DeterministicGeneration206(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.pages = gen.generate(quiet_log())

    def test_repeated_in_process_runs_are_byte_identical(self):
        for _ in range(3):
            again = gen.generate(quiet_log())
            self.assertEqual(
                {k: v.encode("utf-8") for k, v in again.items()},
                {k: v.encode("utf-8") for k, v in self.pages.items()},
            )

    def test_repeated_script_runs_and_unrelated_env_give_the_same_bytes(self):
        with tempfile.TemporaryDirectory() as tmp:
            outputs = {}
            for label, env in (
                ("plain-1", base_env()),
                ("plain-2", base_env()),
                ("utc-c", base_env(TZ="UTC", LANG="C", LC_ALL="C")),
                ("noisy", base_env(**NOISY_ENV)),
            ):
                out = Path(tmp) / label
                result = run_gen("--output", str(out), env=env)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(result.stdout, "wrote 4 man pages\n")
                outputs[label] = read_tree(out)
        expected = {k: v.encode("utf-8") for k, v in self.pages.items()}
        for label, tree in outputs.items():
            with self.subTest(run=label):
                self.assertEqual(tree, expected)

    def test_wall_clock_does_not_change_the_bytes(self):
        clocks = {
            "1999-12-31": 946_684_799.0,  # 1999-12-31T23:59:59Z
            "2042-02-03": 2_275_041_600.0,  # 2042-02-03T12:00:00Z
        }
        with tempfile.TemporaryDirectory() as tmp:
            for label, epoch in clocks.items():
                with self.subTest(clock=label):
                    out = Path(tmp) / label
                    result = run_gen(
                        "--output",
                        str(out),
                        env=base_env(TZ="UTC"),
                        clock=epoch,
                    )
                    self.assertEqual(result.returncode, 0, result.stderr)
                    # The fake clock was in force while the generator ran.
                    self.assertIn(f"clock={label}\n", result.stderr)
                    self.assertIn(f"package_clock={label}\n", result.stderr)
                    self.assertEqual(
                        read_tree(out),
                        {k: v.encode("utf-8") for k, v in self.pages.items()},
                    )

    def test_every_th_line_carries_page_date(self):
        self.assertRegex(gen.PAGE_DATE, r"^\d{4}-\d{2}-\d{2}$")
        self.assertEqual(set(self.pages), set(SHIPPED))
        for filename, text in self.pages.items():
            with self.subTest(page=filename):
                self.assertEqual(text.count(".TH "), 1)
                self.assertIn(f' 1 "{gen.PAGE_DATE}" ', th_line(text))
                # PAGE_DATE is the only date anywhere in the page.
                self.assertEqual(set(DATE.findall(text)), {gen.PAGE_DATE})

    def test_the_date_comes_only_from_page_date(self):
        # Moving PAGE_DATE moves exactly the .TH line and nothing else.
        original = gen.PAGE_DATE
        try:
            gen.PAGE_DATE = OTHER_DATE
            moved = gen.generate(quiet_log())
        finally:
            gen.PAGE_DATE = original
        for filename, text in self.pages.items():
            with self.subTest(page=filename):
                new = moved[filename]
                self.assertIn(f' 1 "{OTHER_DATE}" ', th_line(new))
                self.assertEqual(
                    new.replace(th_line(new), th_line(text)),
                    text,
                )


class DriftDetection206(unittest.TestCase):
    def check(self, directory, page_date=None):
        """gen_manpages.main(--check) in-process -> (rc, stderr)."""
        original = gen.PAGE_DATE
        err = io.StringIO()
        try:
            if page_date is not None:
                gen.PAGE_DATE = page_date
            with (
                contextlib.redirect_stdout(io.StringIO()),
                contextlib.redirect_stderr(err),
            ):
                rc = gen.main(["--check", "--output", str(directory)])
        finally:
            gen.PAGE_DATE = original
        return rc, err.getvalue()

    def regenerate(self, directory, page_date=None):
        original = gen.PAGE_DATE
        try:
            if page_date is not None:
                gen.PAGE_DATE = page_date
            with (
                contextlib.redirect_stdout(io.StringIO()),
                contextlib.redirect_stderr(io.StringIO()),
            ):
                return gen.main(["--output", str(directory)])
        finally:
            gen.PAGE_DATE = original

    def test_bump_without_regenerating_fails_check_until_regenerated(self):
        # The manual bump checklist: change PAGE_DATE, regenerate, --check.
        with tempfile.TemporaryDirectory() as tmp:
            pages = Path(tmp) / "man1"
            self.assertEqual(self.regenerate(pages), 0)
            self.assertEqual(self.check(pages), (0, ""))
            rc, err = self.check(pages, page_date=OTHER_DATE)
            self.assertEqual(rc, 1)
            for filename in SHIPPED:
                self.assertIn(f"gen_manpages: drift in {filename}\n", err)
            self.assertEqual(self.regenerate(pages, page_date=OTHER_DATE), 0)
            self.assertEqual(self.check(pages, page_date=OTHER_DATE), (0, ""))
            self.assertEqual(self.check(pages)[0], 1)

    def test_check_script_fails_on_edited_date_and_passes_after_regenerate(self):
        with tempfile.TemporaryDirectory() as tmp:
            pages = Path(tmp) / "man1"
            env = base_env()
            self.assertEqual(run_gen("--output", str(pages), env=env).returncode, 0)
            good = read_tree(pages)
            page = pages / "parking-report-106.1"
            page.write_bytes(
                page.read_bytes().replace(
                    f'"{gen.PAGE_DATE}"'.encode(), f'"{OTHER_DATE}"'.encode(), 1
                )
            )
            self.assertNotEqual(page.read_bytes(), good["parking-report-106.1"])
            result = run_gen("--check", "--output", str(pages), env=env)
            self.assertEqual(result.returncode, 1)
            self.assertIn(
                "gen_manpages: drift in parking-report-106.1\n", result.stderr
            )
            self.assertEqual(run_gen("--output", str(pages), env=env).returncode, 0)
            self.assertEqual(read_tree(pages), good)
            result = run_gen("--check", "--output", str(pages), env=env)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stdout, "4 man pages up to date\n")


@unittest.skipUnless(MAN1.is_dir(), "man/ is not copied into the Docker test image")
class CommittedPages206(unittest.TestCase):
    def test_committed_th_lines_carry_page_date(self):
        for filename in SHIPPED:
            with self.subTest(page=filename):
                text = (MAN1 / filename).read_text(encoding="utf-8")
                self.assertIn(f' 1 "{gen.PAGE_DATE}" ', th_line(text))

    def test_drift_in_a_copy_of_the_committed_pages_is_detected_and_restored(self):
        before = sha256_tree(MAN1)
        with tempfile.TemporaryDirectory() as tmp:
            copy = Path(tmp) / "man1"
            shutil.copytree(MAN1, copy)
            env = base_env()
            result = run_gen("--check", "--output", str(copy), env=env)
            self.assertEqual(result.returncode, 0, result.stderr)
            page = copy / "parking-report.1"
            page.write_bytes(
                page.read_bytes().replace(
                    f'"{gen.PAGE_DATE}"'.encode(), f'"{OTHER_DATE}"'.encode(), 1
                )
            )
            result = run_gen("--check", "--output", str(copy), env=env)
            self.assertEqual(result.returncode, 1)
            self.assertIn("gen_manpages: drift in parking-report.1\n", result.stderr)
            self.assertEqual(run_gen("--output", str(copy), env=env).returncode, 0)
            self.assertEqual(sha256_tree(copy), before)
            result = run_gen("--check", "--output", str(copy), env=env)
            self.assertEqual(result.returncode, 0, result.stderr)
        # The committed tree was only read.
        self.assertEqual(sha256_tree(MAN1), before)


if __name__ == "__main__":
    unittest.main()
